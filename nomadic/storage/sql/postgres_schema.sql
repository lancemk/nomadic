CREATE TABLE IF NOT EXISTS chat_sessions (
    id TEXT PRIMARY KEY,
    chat_name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'paused', 'closed', 'archived')),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    started_at TEXT,
    ended_at TEXT,
    model TEXT,
    host TEXT,
    port INTEGER,
    temperature DOUBLE PRECISION,
    top_p DOUBLE PRECISION,
    max_tokens INTEGER,
    max_skill_chars INTEGER,
    max_context_tokens INTEGER,
    context_recompress_to INTEGER,
    system_prompt TEXT NOT NULL,
    summary TEXT,
    message_count INTEGER NOT NULL DEFAULT 0,
    user_turn_count INTEGER NOT NULL DEFAULT 0,
    assistant_turn_count INTEGER NOT NULL DEFAULT 0,
    tool_event_count INTEGER NOT NULL DEFAULT 0,
    last_message_at TEXT,
    metadata_json TEXT
);

CREATE INDEX IF NOT EXISTS idx_chat_sessions_status_updated_at
    ON chat_sessions(status, updated_at DESC);

CREATE INDEX IF NOT EXISTS idx_chat_sessions_last_message_at
    ON chat_sessions(last_message_at DESC);

CREATE TABLE IF NOT EXISTS chat_messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL
        REFERENCES chat_sessions(id) ON DELETE CASCADE,
    message_index INTEGER NOT NULL,
    role TEXT NOT NULL
        CHECK (role IN ('system', 'user', 'assistant', 'tool')),
    content_type TEXT NOT NULL,
    content_text TEXT,
    content_json TEXT,
    raw_request_json TEXT,
    raw_response_json TEXT,
    token_estimate INTEGER,
    created_at TEXT NOT NULL,
    parent_message_id INTEGER
        REFERENCES chat_messages(id) ON DELETE SET NULL,
    metadata_json TEXT,
    UNIQUE (session_id, message_index)
);

CREATE INDEX IF NOT EXISTS idx_chat_messages_session_index
    ON chat_messages(session_id, message_index);

CREATE INDEX IF NOT EXISTS idx_chat_messages_session_created_at
    ON chat_messages(session_id, created_at DESC);

CREATE TABLE IF NOT EXISTS chat_attachments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL
        REFERENCES chat_sessions(id) ON DELETE CASCADE,
    message_id INTEGER
        REFERENCES chat_messages(id) ON DELETE SET NULL,
    kind TEXT NOT NULL,
    file_path TEXT,
    file_name TEXT,
    mime_type TEXT,
    sha256 TEXT,
    byte_size INTEGER,
    created_at TEXT NOT NULL,
    metadata_json TEXT
);

CREATE INDEX IF NOT EXISTS idx_chat_attachments_session_message
    ON chat_attachments(session_id, message_id);

CREATE TABLE IF NOT EXISTS chat_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL
        REFERENCES chat_sessions(id) ON DELETE CASCADE,
    message_id INTEGER
        REFERENCES chat_messages(id) ON DELETE SET NULL,
    event_type TEXT NOT NULL,
    event_name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'ok',
    payload_json TEXT,
    created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_chat_events_session_created_at
    ON chat_events(session_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_chat_events_type_created_at
    ON chat_events(event_type, created_at DESC);
